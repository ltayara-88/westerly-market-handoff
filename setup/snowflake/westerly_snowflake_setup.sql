-- =====================================================================
-- Westerly Market: Snowflake demo setup (synthetic data only)
-- Creates: orders, order items, customers, products, store inventory,
-- plus a read-only role/user for Data 360 zero copy.
-- Run top to bottom in a Snowflake worksheet as ACCOUNTADMIN.
-- Order dates are relative to today, so "last 30 days" insights stay true.
-- =====================================================================

USE ROLE ACCOUNTADMIN;

-- 1. Compute: smallest warehouse, pauses after 60s idle to save credits
CREATE WAREHOUSE IF NOT EXISTS WESTERLY_WH
  WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;
USE WAREHOUSE WESTERLY_WH;

-- 2. Database and schemas
CREATE DATABASE IF NOT EXISTS WESTERLY_MARKET;
CREATE SCHEMA IF NOT EXISTS WESTERLY_MARKET.SALES;      -- customers, orders
CREATE SCHEMA IF NOT EXISTS WESTERLY_MARKET.INVENTORY;  -- products, stock
USE DATABASE WESTERLY_MARKET;

-- 3. Tables
CREATE OR REPLACE TABLE SALES.CUSTOMERS (
  CUSTOMER_ID   VARCHAR PRIMARY KEY,   -- same ID the website sends in the Data 360 identity event
  EMAIL         VARCHAR,
  FIRST_NAME    VARCHAR,
  LAST_NAME     VARCHAR,
  HOME_STORE_ID VARCHAR,
  CREATED_AT    TIMESTAMP_NTZ,
  LAST_MODIFIED TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE OR REPLACE TABLE INVENTORY.PRODUCTS (
  SKU           VARCHAR PRIMARY KEY,   -- matches the SKUs on the website
  PRODUCT_NAME  VARCHAR,
  CATEGORY      VARCHAR,
  PACK_SIZE     VARCHAR,
  PRICE         NUMBER(10,2),
  REGULAR_PRICE NUMBER(10,2),           -- set when the item is on this week's deal
  LAST_MODIFIED TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE OR REPLACE TABLE INVENTORY.STORE_INVENTORY (
  INVENTORY_ID      VARCHAR PRIMARY KEY, -- STORE_ID || '-' || SKU
  STORE_ID          VARCHAR,
  SKU               VARCHAR,
  QUANTITY_ON_HAND  NUMBER,              -- 0 = unavailable on the website
  LAST_MODIFIED     TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE OR REPLACE TABLE SALES.ORDERS (
  ORDER_ID      VARCHAR PRIMARY KEY,
  CUSTOMER_ID   VARCHAR,
  STORE_ID      VARCHAR,
  ORDER_DATE    TIMESTAMP_NTZ,
  ORDER_STATUS  VARCHAR,                 -- Delivered | Picked | Not yet picked
  CHANNEL       VARCHAR,                 -- Online
  ORDER_TOTAL   NUMBER(10,2),
  ITEM_COUNT    NUMBER,
  LAST_MODIFIED TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE OR REPLACE TABLE SALES.ORDER_ITEMS (
  ORDER_ITEM_ID VARCHAR PRIMARY KEY,
  ORDER_ID      VARCHAR,
  SKU           VARCHAR,
  QUANTITY      NUMBER,
  UNIT_PRICE    NUMBER(10,2),
  LINE_TOTAL    NUMBER(10,2),
  LAST_MODIFIED TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

