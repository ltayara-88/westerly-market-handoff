-- 9. Check the data
SELECT COUNT(*) AS products FROM INVENTORY.PRODUCTS;                         -- 52
SELECT STORE_ID, SKU, QUANTITY_ON_HAND FROM INVENTORY.STORE_INVENTORY
  WHERE QUANTITY_ON_HAND <= 2 ORDER BY STORE_ID, SKU;                         -- zero / low stock
SELECT CUSTOMER_ID, COUNT(*) AS orders_last_30_days,
       IFF(COUNT(*) > 5, 'Top Shopper', 'Regular') AS shopper_tier,
       ROUND(AVG(ORDER_TOTAL), 2) AS avg_cart_value
  FROM SALES.ORDERS
  WHERE ORDER_DATE >= DATEADD(day, -30, CURRENT_TIMESTAMP())
  GROUP BY CUSTOMER_ID ORDER BY orders_last_30_days DESC;                     -- CUST_001 = Top Shopper

